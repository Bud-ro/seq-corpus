using System;
using NI.MeasurementFoundation.DataManagement;
using NI.MeasurementInstrumentation.HAL.DaqHandlers.Enums;
using NI.PCBAMeasurements.Apis.TestToolkitApi.Common.Enums;
using NI.PCBAMeasurements.Apis.TestToolkitApi.Common.Structs;
using NI.PCBAMeasurements.Apis.TestToolkitApi.Measurements.FrequencyDomainMeasurements.Structs;
using NI.PCBAMeasurements.Apis.TestToolkitApi.Generations.SignalVoltageGenerations.Enums;
using NI.PCBAMeasurements.Apis.TestToolkitApi.Generations.SignalVoltageGenerations.Structs;
using PCBATestToolkitApi.Measurements.FrequencyDomainMeasurements;
using PCBATestToolkitApi.Measurements.FrequencyDomainMeasurements.Constants;
using PCBATestToolkitApi.Generations.SignalVoltageGenerations;
using PCBATestToolkitApi.Generations.SignalVoltageGenerations.Constants;
using ConstantsForDcVoltageGenerations = PCBATestToolkitApi.Generations.DcVoltageGenerations.Constants.ConstantsForDcVoltageGenerations;

namespace PCBATestToolkitAutomation.Audio_Test
{
    /// <summary>
    /// Example of an execution of the audio line check test
    /// </summary>
    internal class AudioLineCheckTestSequence : AbstractSequence
    {
        /// <inheritdoc cref="AbstractSequence.Execute"/>
        public override void Execute()
        {
            /* Setup */

            /*** Configure the artifacts
             *
             *  by using the class NI.Measurement.Foundation.FileSystemMeasurementArtifactsManager,
             * you are able to give a path where the files will be saved.
             *
             */

            // this variable will allow to date the results folder and avoid deletion.
            String now = DateTime.Now.ToString("dd-MM-yyyy-hh-mm-ss");

            // results folder for Signal Voltage Generation
            string signalVoltageGenerationResultFile = NI.Core.Utilities.FileSystem.PathUtils.Combine(
                NI.Core.Utilities.FileSystem.FolderUtils.GetExecutingAssemblyDirectory(), $"DCVG-{now}");

            // results folder for Frequency Domain Measurement
            string frequencyDomainMeasurementResultFile = NI.Core.Utilities.FileSystem.PathUtils.Combine(
                NI.Core.Utilities.FileSystem.FolderUtils.GetExecutingAssemblyDirectory(), $"FDM-{now}"); 

            FileSystemMeasurementArtifactsManager signalVoltageGenerationArtifactsManager =
                new FileSystemMeasurementArtifactsManager(signalVoltageGenerationResultFile);

            FileSystemMeasurementArtifactsManager frequencyDomainMeasurementArtifactsManager =
                new FileSystemMeasurementArtifactsManager(frequencyDomainMeasurementResultFile);

            /*** Initialization
             *
             *  Initializes the demonstration of Frequency Domain Measurement (extraction of tones)
             * of captured Analog (Audio) signal generated by Analog Output (generates sine waves tones)
             * module with Hardware Trigger
             *
             */

            // need to be modified according your configuration
            string signalVoltageGenerationPhysicalChannel = "TS_AudioLineIn0";

            // need to be modified according your configuration
            string frequencyDomainMeasurementPhysicalChannel = "TP_AudioLineOut0";

            SignalVoltageGeneration signalVoltageGeneration = SignalVoltageGeneration.CreateInstance(signalVoltageGenerationPhysicalChannel);
            FrequencyDomainMeasurement frequencyDomainMeasurement = FrequencyDomainMeasurement.CreateInstance(frequencyDomainMeasurementPhysicalChannel);

            signalVoltageGeneration.ExternalComponents.ArtifactsManagers.AttachArtifactsManager(signalVoltageGenerationArtifactsManager);
            frequencyDomainMeasurement.ExternalComponents.ArtifactsManagers.AttachArtifactsManager(frequencyDomainMeasurementArtifactsManager);

            /* Main */

            /*** 
             *
             * Note to run with Hardware: Review the configuration & update Trigger
             * Source settings based on NI MAX
             *
             */

            // configure Freq Domain Measurement settings to wait for Hardware Trigger
            FrequencyDomainMeasurementConfigurationParameters
                frequencyDomainMeasurementConfigurationParameters =
                    new FrequencyDomainMeasurementConfigurationParameters(
                        channelAndTerminalSettings: ConstantsForFrequencyDomainMeasurements
                            .DefaultFrequencyDomainMeasurementChannelAndTerminalSettings,
                        options: new MeasurementOptions(
                            EMeasurementExecutionType.ConfigureOnly,
                            EMeasurementAnalysisRequirement.SkipAnalysis),
                        timingSettings: ConstantsForFrequencyDomainMeasurements
                            .DefaultFrequencyDomainMeasurementTimingSettings,
                        triggerSettings: new MeasurementTriggerSettings(
                            EMeasurementTriggerType.DigitalStartTrigger,
                            "/Sim_TS/ao/StartTrigger",
                            EDigitalEdgeStartTriggerEdge.Rising));

            frequencyDomainMeasurement.ConfigureAndMeasure(frequencyDomainMeasurementConfigurationParameters);

            // Generates sine wave and Trigger to initiate measurement
            SignalVoltageGenerationConfigurationParameters
                signalVoltageGenerationConfigurationParameters =
                    new SignalVoltageGenerationConfigurationParameters(
                        rangeSettings: ConstantsForDcVoltageGenerations
                            .DefaultVoltageGenerationRangeSettings,
                        timingSettings: ConstantsForSignalVoltageGenerations
                            .DefaultSignalVoltageGenerationTimingSettings,
                        triggerSettings: new MeasurementTriggerSettings(
                            EMeasurementTriggerType.NoTrigger, "NA",
                            EDigitalEdgeStartTriggerEdge.Rising),
                        signalGenerationSettings: new SignalGenerationSettings(
                            ESignalGenerationWaveformType.PeriodicWaveform,
                            0.1, 0.0,
                            new PeriodicWaveformSettings(
                                EPeriodicWaveformType.SineWaveform, 1000, 1, 0,
                                50), Array.Empty<SignalToneSettings>()));

            signalVoltageGeneration.ConfigureAndGenerate(signalVoltageGenerationConfigurationParameters);

            // Measures the analog input voltage waveforms (started measure when signal voltage generation sends
            // trigger after source) and returns Freq Domain analysis 
            frequencyDomainMeasurementConfigurationParameters =
                    new FrequencyDomainMeasurementConfigurationParameters(
                        channelAndTerminalSettings: ConstantsForFrequencyDomainMeasurements
                            .DefaultFrequencyDomainMeasurementChannelAndTerminalSettings,
                        options: new MeasurementOptions(
                            EMeasurementExecutionType.MeasureOnly,
                            EMeasurementAnalysisRequirement.ProceedToAnalysis),
                        timingSettings: ConstantsForFrequencyDomainMeasurements
                            .DefaultFrequencyDomainMeasurementTimingSettings,
                        triggerSettings: new MeasurementTriggerSettings(
                            EMeasurementTriggerType.NoTrigger,
                            "NA",
                            EDigitalEdgeStartTriggerEdge.Rising));

            frequencyDomainMeasurement.ConfigureAndMeasure(frequencyDomainMeasurementConfigurationParameters);

            /* Cleanup */

            /*** Close all tasks ***/
            frequencyDomainMeasurement.Close();
            signalVoltageGeneration.Close();

            // Power down channel
            PowerDownChannels.PowerDownAllAoChannelsForDcVoltageGeneration(signalVoltageGenerationPhysicalChannel);
        }
    }
}
